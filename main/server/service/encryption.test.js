test("decodeWebSocketMessage decodes data correctly", () => {
  const expectedData = { type: "chat", text: "test message\0" };
  const actualData = Encryption.decodeWebSocketMessage(Buffer.from([
    0x81, 0x0e, 0x74, 0x65, 0x73, 0x74, 0x20, 0x6d, 0x65, 0x73, 0x73, 0x61, 0x67, 0x65, 0x00,
  ]));
  assert.deepEqual(actualData, expectedData);
});

test('should encode and decode a giant random string', () => {
  const randomString = generateRandomString(65536);
  const encodedMessage = Encryption.encodeWebSocketMessage({ text: randomString });
  const decodedMessage = Encryption.decodeWebSocketMessage(encodedMessage);

  assert.deepEqual(decodedMessage.text, randomString);
});

function generateRandomString(length) {
  const characters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  let result = '';
  for (let i = 0; i < length; i += 1) {
    result += characters.charAt(Math.floor(Math.random() * characters.length));
  }
  return result;
}